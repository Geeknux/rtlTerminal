#!/usr/bin/env bash
# هر خط با «الف» شروع می‌شود؛ الف باید سمت راست دیده شود.
a=(الف ب پ ت ث ج چ ح خ د ذ ر ز ژ س ش ص ض ط ظ ع غ ف ق ک گ ل م ن و ه ی)
mk() { s="الف"; for ((i=1;i<$1;i++)); do s="$s ${a[i]}"; done; echo "$s"; }
mk 10; mk 20; mk 33; echo "این یک جمله است"
sleep 1
echo "این یک جملهٔ نسبتاً طولانی فارسی است که باید در لبهٔ ترمینال به خط بعد برود و ترتیب خواندن آن همچنان از راست به چپ باشد"
